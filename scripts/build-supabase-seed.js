import { readFile, writeFile } from "node:fs/promises";

const sourcePath = new URL("../data/dtc-codes.json", import.meta.url);
const outputPath = new URL("../supabase/seed.sql", import.meta.url);
const batchSize = 500;

const content = await readFile(sourcePath, "utf8");
const codes = JSON.parse(content);

if (!codes || Array.isArray(codes) || typeof codes !== "object") {
  throw new TypeError("База DTC должна быть объектом кодов");
}

const entries = Object.entries(codes).sort(([left], [right]) =>
  left.localeCompare(right),
);

for (const [code, description] of entries) {
  if (!/^[PBCU][0-9A-F]{4}$/.test(code)) {
    throw new TypeError(`Некорректный DTC-код: ${code}`);
  }

  if (typeof description !== "string" || !description.trim()) {
    throw new TypeError(`Пустое описание DTC-кода: ${code}`);
  }

  if (description.includes("\u0000")) {
    throw new TypeError(`Описание DTC-кода содержит нулевой байт: ${code}`);
  }
}

const statements = [
  "-- Generated by scripts/build-supabase-seed.js. Do not edit manually.",
  "-- Source: data/dtc-codes.json",
  "",
  "begin;",
];

for (let offset = 0; offset < entries.length; offset += batchSize) {
  const batch = entries.slice(offset, offset + batchSize);
  const values = batch
    .map(
      ([code, description]) =>
        `  (${toSqlLiteral(code)}, ${toSqlLiteral(description)})`,
    )
    .join(",\n");

  statements.push(
    "",
    "insert into public.dtc_codes (code, description)",
    "values",
    values,
    "on conflict (code) do update",
    "set description = excluded.description;",
  );
}

statements.push("", "commit;", "");

await writeFile(outputPath, statements.join("\n"), "utf8");
console.log(`Создан Supabase seed: ${entries.length} универсальных кодов`);

function toSqlLiteral(value) {
  return `'${value.replaceAll("'", "''")}'`;
}
